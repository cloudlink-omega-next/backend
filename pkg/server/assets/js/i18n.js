window.addEventListener('error', function(event) {
  console.error('[Global Error]', event.message, 'at', event.filename + ':' + event.lineno + ':' + event.colno);
  if (event.error && event.error.stack) {
    console.error('[Stack]', event.error.stack);
  }
  if (event.target && event.target.src) {
    console.error('[Script src]', event.target.src);
  } else if (event.target && event.target.href) {
    console.error('[Link href]', event.target.href);
  }
});

function getI18nLang() {
  return document.documentElement.lang === 'zh' ? 'zh' : 'en';
}

function t(key) {
  const lang = getI18nLang();
  return window.i18nTranslations[lang]?.[key] || window.i18nTranslations['en']?.[key] || key;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    const key = el.getAttribute('data-i18n');
    if (window.i18nTranslations['en'][key]) {
      el.textContent = t(key);
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    const key = el.getAttribute('data-i18n-html');
    if (window.i18nTranslations['en'][key]) {
      el.innerHTML = t(key);
    }
  });

  const currentLang = getI18nLang();
  const targetLang = currentLang === 'en' ? 'zh' : 'en';
  const langToggleText = t('lang_' + targetLang);
  document.querySelectorAll('#lang-toggle span, #mobile-lang-toggle span').forEach(function(el) {
    el.textContent = langToggleText;
  });
}

function setI18nLang(lang) {
  document.documentElement.lang = lang;
  localStorage.setItem('language', lang);
  applyI18n();
}

document.addEventListener('DOMContentLoaded', function() {
  const savedLang = localStorage.getItem('language');
  if (savedLang && (savedLang === 'en' || savedLang === 'zh')) {
    setI18nLang(savedLang);
  } else {
    setI18nLang('en');
  }
  applyI18n();
});

